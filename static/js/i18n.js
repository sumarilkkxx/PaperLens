    function t(locale, key, params) {
        var text = (TRANSLATIONS[locale] && TRANSLATIONS[locale][key]) || (TRANSLATIONS.en && TRANSLATIONS.en[key]) || key;
        if (params && typeof params === 'object') {
            Object.keys(params).forEach(function (k) {
                text = text.replace(new RegExp('\\{' + k + '\\}', 'g'), String(params[k]));
            });
        }
        return text;
    }

    function applyTranslations(locale) {
        if (!locale || !TRANSLATIONS[locale]) {
            locale = 'en';
        }
        document.querySelectorAll('[data-i18n]').forEach(function (el) {
            var key = el.getAttribute('data-i18n');
            if (key) {
                el.textContent = t(locale, key);
            }
        });
        document.querySelectorAll('[data-i18n-placeholder]').forEach(function (el) {
            var key = el.getAttribute('data-i18n-placeholder');
            if (key) {
                el.placeholder = t(locale, key);
            }
        });
        document.querySelectorAll('[data-i18n-title]').forEach(function (el) {
            var key = el.getAttribute('data-i18n-title');
            if (key) {
                el.title = t(locale, key);
            }
        });
        document.documentElement.lang = locale === 'zh_CN' ? 'zh-Hans' : 'en';
        if (typeof window.__LOCALE !== 'undefined') {
            window.__LOCALE = locale;
        }
        var logo = document.getElementById('navbar-logo');
        if (logo && logo.src) {
            if (locale === 'zh_CN') {
                logo.src = logo.src.replace(/hompage_logo\.svg/, 'hompage_logo_zh.svg');
            } else {
                logo.src = logo.src.replace(/hompage_logo_zh\.svg/, 'hompage_logo.svg');
            }
        }
        var titleKey = 'page_title';
        if (TRANSLATIONS[locale] && TRANSLATIONS[locale][titleKey]) {
            document.title = TRANSLATIONS[locale][titleKey];
        } else if (TRANSLATIONS.en && TRANSLATIONS.en[titleKey]) {
            document.title = TRANSLATIONS.en[titleKey];
        }
    }

    function getLocale() {
        return window.__LOCALE || 'en';
    }

    window.PaperLensI18n = {
        t: t,
        applyTranslations: applyTranslations,
        getLocale: getLocale,
        TRANSLATIONS: TRANSLATIONS
    };
    window.applyTranslations = applyTranslations;
    window.getLocale = getLocale;
    window.__t = function (key, params) {
        return t(getLocale(), key, params);
    };

    if (document.readyState === 'loading') {
        document.addEventListener('DOMContentLoaded', function () {
            applyTranslations(getLocale());
        });
    } else {
        applyTranslations(getLocale());
    }
